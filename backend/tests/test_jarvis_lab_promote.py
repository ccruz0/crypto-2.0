def test_promote_refuses_stub(exec_db, monkeypatch):
    monkeypatch.setenv("JARVIS_ENABLED", "true")
    monkeypatch.setenv("JARVIS_PROMOTE_PR_ENABLED", "true")
    task_id = _seed_waiting_task(STUB_PATCH)
    # Force a lab-passed state without send_to_lab (which would refuse stub).
    task = get_execution_task(task_id)
    plan = dict(task.get("plan") or {})
    plan["lab_trial"] = {
        "status": "passed",
        "tests_passed": True,
        "sandbox_applied": True,
        "branch_name": "jarvis/task-stub",
        "workdir": "/tmp/x",
        "forbidden_check": {"passed": True},
    }
    _update_task(task_id, plan_json=plan)
    transition_task_status(task_id, TaskLifecycleState.APPLYING_PATCH)
    transition_task_status(task_id, TaskLifecycleState.SANDBOX_TESTING)
    transition_task_status(task_id, TaskLifecycleState.WAITING_FOR_PR_APPROVAL)
    from app.jarvis.execution.persistence import record_approval

    record_approval(task_id=task_id, decision="sent_to_lab", actor_id="tester", comment="forced")
    with pytest.raises(ValueError, match="stub|real patch"):
        promote_to_production(task_id, actor_id="tester", mock_pr=True)


