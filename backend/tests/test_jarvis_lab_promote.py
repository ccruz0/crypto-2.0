def test_promote_opens_mock_pr_after_lab_green(exec_db, monkeypatch):
    monkeypatch.setenv("JARVIS_PROMOTE_PR_ENABLED", "true")
    monkeypatch.setenv("JARVIS_PR_CREATION_ENABLED", "false")
    monkeypatch.setenv("JARVIS_GITHUB_WRITE_ENABLED", "false")
    task_id = _seed_waiting_task(REAL_PATCH)
    _run_lab_pass(task_id, monkeypatch)

    lab = get_lab_trial_status(task_id)
    assert lab["promote_available"] is True

    result = promote_to_production(task_id, actor_id="tester", mock_pr=True)
    assert result["status"] == TaskLifecycleState.COMPLETED.value
    assert result["current_step"] == "lab_promoted_awaiting_human_merge"
    assert "merge" in (result.get("final_answer") or "").lower()
    lab = result["lab_trial"]
    assert lab["status"] == "promoted"
    assert lab["pr_url"]
    assert lab["can_promote"] is False
    assert lab["promote_available"] is False
    # Broad Gate-2 flags stayed off
    assert lab["safety_flags"]["pr_creation_enabled"] is False
    assert lab["safety_flags"]["github_write_enabled"] is False


