def _seed_waiting_task(patch_content: str, *, workflow: str = "phase4b_patch_proposal") -> str:
    task_id = "lab-promote-0001-aaaa-bbbb-cccccccccccc"
    create_execution_task(task_id=task_id, objective="Promote after LAB", dry_run=True)
    art = create_versioned_artifact(
        task_id=task_id,
        name="patch.diff",
        content=patch_content,
        fmt="text",
        version=1,
    )
    _update_task(
        task_id,
        plan_json={"workflow_type": workflow},
        artifacts_json=[art],
        approval_required=True,
        approval_status="pending",
    )
    transition_task_status(task_id, TaskLifecycleState.PLANNING)
    transition_task_status(task_id, TaskLifecycleState.INVESTIGATING)
    transition_task_status(task_id, TaskLifecycleState.PATCH_READY)
    transition_task_status(task_id, TaskLifecycleState.REVIEWING)
    transition_task_status(task_id, TaskLifecycleState.WAITING_FOR_APPROVAL)
    return task_id


